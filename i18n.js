  var LANG_LABELS = {
    en: "English",
    "zh-Hans": "简体中文",
    "zh-Hant": "繁體中文",
    ja: "日本語",
  };

  function detectLanguage() {
    var saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;

    var langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
    for (var i = 0; i < langs.length; i++) {
      var raw = String(langs[i] || "").toLowerCase();
      if (!raw) continue;
      if (raw.indexOf("ja") === 0) return "ja";
      if (raw.indexOf("zh") === 0) {
        if (raw.indexOf("hant") !== -1 || raw.indexOf("tw") !== -1 || raw.indexOf("hk") !== -1 || raw.indexOf("mo") !== -1) {
          return "zh-Hant";
        }
        return "zh-Hans";
      }
      if (raw.indexOf("en") === 0) return "en";
    }
    return "en";
  }

  function t(lang, key) {
    var table = STRINGS[lang] || STRINGS.en;
    return table[key] != null ? table[key] : (STRINGS.en[key] || "");
  }

  function applyLanguage(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = "en";
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dataset.lang = lang;
    document.body.style.fontFamily = FONT_STACKS[lang] || FONT_STACKS.en;

    var page = document.body.dataset.page || "index";
    document.title = t(lang, "meta." + page + ".title") || document.title;

    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) {
      var desc = t(lang, "meta." + page + ".description");
      if (desc) metaDesc.setAttribute("content", desc);
    }

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = t(lang, el.getAttribute("data-i18n"));
      if (value) el.textContent = value;
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var value = t(lang, el.getAttribute("data-i18n-html"));
      if (value) el.innerHTML = value;
    });

    var toggle = document.getElementById("langToggle");
    if (toggle) {
      var current = toggle.querySelector(".lang-current");
      if (current) current.textContent = LANG_LABELS[lang] || lang;
    }

    document.querySelectorAll(".lang-menu [data-lang]").forEach(function (btn) {
      var active = btn.getAttribute("data-lang") === lang;
      btn.classList.toggle("active", active);
      btn.setAttribute("aria-selected", active ? "true" : "false");
    });
  }

  function closeLangMenu() {
    var menu = document.getElementById("langMenu");
    var toggle = document.getElementById("langToggle");
    if (!menu || !toggle) return;
    menu.hidden = true;
    toggle.setAttribute("aria-expanded", "false");
  }

  function openLangMenu() {
    var menu = document.getElementById("langMenu");
    var toggle = document.getElementById("langToggle");
    if (!menu || !toggle) return;
    menu.hidden = false;
    toggle.setAttribute("aria-expanded", "true");
  }

  function initLangSwitcher() {
    var toggle = document.getElementById("langToggle");
    var menu = document.getElementById("langMenu");
    if (!toggle || !menu) return;

    toggle.addEventListener("click", function (e) {
      e.stopPropagation();
      if (menu.hidden) openLangMenu();
      else closeLangMenu();
    });

    menu.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        applyLanguage(btn.getAttribute("data-lang"));
        closeLangMenu();
      });
    });

    document.addEventListener("click", closeLangMenu);
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") closeLangMenu();
    });
  }

  window.FlightModeI18n = {
    detectLanguage: detectLanguage,
    applyLanguage: applyLanguage,
    supported: SUPPORTED,
  };

  document.addEventListener("DOMContentLoaded", function () {
    applyLanguage(detectLanguage());
    initLangSwitcher();
  });
